export const DEFAULT_TEMPLATE_ID = "konoha-ink";

export const TEMPLATE_IDS = TEMPLATES.map((template) => template.id);

const TEMPLATE_MAP = new Map(TEMPLATES.map((template) => [template.id, template]));

export function getTemplate(id: string | null | undefined): TemplateDefinition {
  if (!id) return TEMPLATES[0];
  return TEMPLATE_MAP.get(id) ?? TEMPLATES[0];
}

export function templateCountByFamily(family: TemplateFamily) {
  return TEMPLATES.filter((template) => template.family === family).length;
}
